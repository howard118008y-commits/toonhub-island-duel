export function characterVoice(id, kind) {
  const lines = id === 101 || id === '101'
    ? TOKEN_VOICES
    : Object.hasOwn(CHARACTER_VOICES, id) ? CHARACTER_VOICES[id] : GENERIC_VOICES;
  return typeof lines[kind] === 'string' ? lines[kind] : GENERIC_VOICES.summon;
}
